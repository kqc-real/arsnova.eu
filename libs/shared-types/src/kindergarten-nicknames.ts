function selectableAnimals(locale: AppLocale) {
  const languageIndex = APP_LOCALES.indexOf(locale);
  return KINDERGARTEN_NICKNAMES_BY_ID[locale].flatMap((name, animalId) =>
    retiredAnimalIds.has(animalId)
      ? []
      : [{ name: updatedNames[animalId]?.[languageIndex] ?? name, animalId }],
  );
}

