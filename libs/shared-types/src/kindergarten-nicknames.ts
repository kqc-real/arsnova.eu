export function getKindergartenCounterId(animalId: number): number {
  return sharedCounterIds.get(animalId) ?? animalId;
}

const animalIdsByName = new Map<string, number>();
for (const animals of Object.values(KINDERGARTEN_ANIMALS)) {
  for (const { name, animalId } of animals) {
    animalIdsByName.set(name, getKindergartenCounterId(animalId));
  }
}

const LEGACY_PICKER_NICKNAME_MAX_LENGTH = 30;
const legacyAnimalsByName = new Map<string, { animalId: number; name: string }>();
const ambiguousLegacyNames = new Set<string>();

function registerLegacyAnimal(
  legacyName: string,
  animal: { animalId: number; name: string },
): void {
  if (ambiguousLegacyNames.has(legacyName)) return;
  const existing = legacyAnimalsByName.get(legacyName);
  if (existing && existing.animalId !== animal.animalId) {
    legacyAnimalsByName.delete(legacyName);
    ambiguousLegacyNames.add(legacyName);
    return;
  }
  if (!existing) legacyAnimalsByName.set(legacyName, animal);
}

for (const locale of APP_LOCALES) {
  const languageIndex = APP_LOCALES.indexOf(locale);
  for (const [animalId, legacyName] of LEGACY_KINDERGARTEN_NICKNAMES[locale].entries()) {
    const currentName =
      updatedNames[animalId]?.[languageIndex] ?? KINDERGARTEN_NICKNAMES_BY_ID[locale][animalId];
    if (!currentName) continue;
    const animal = { animalId, name: currentName };
    registerLegacyAnimal(legacyName, animal);
    // Der Vorgänger-Client kürzte den ausgewählten Picker-Namen vor dem Join auf 30 Zeichen.
    registerLegacyAnimal(
      legacyName.trim().slice(0, LEGACY_PICKER_NICKNAME_MAX_LENGTH).trim(),
      animal,
    );
  }
}

export function getKindergartenAnimalId(name: string, selectedId?: number): number | undefined {
  const defaultId = animalIdsByName.get(name);
  if (selectedId === undefined) return defaultId;
  return defaultId !== undefined && getKindergartenCounterId(selectedId) === defaultId
    ? selectedId
    : undefined;
}

export function getLegacyKindergartenAnimal(
  name: string,
): { animalId: number; name: string } | undefined {
  return legacyAnimalsByName.get(name);
}

export function getKindergartenAnimalNames(counterId: number): readonly string[] {
  const names = new Set<string>();
  for (const locale of APP_LOCALES) {
    for (const { name, animalId } of KINDERGARTEN_ANIMALS[locale]) {
      if (getKindergartenCounterId(animalId) === counterId) {
        names.add(name);
        const previousName = KINDERGARTEN_NICKNAMES_BY_ID[locale][animalId]!;
        const currentId = animalIdsByName.get(previousName);
        if (currentId === undefined || currentId === counterId) names.add(previousName);
      }
    }
  }
  return [...names];
}

